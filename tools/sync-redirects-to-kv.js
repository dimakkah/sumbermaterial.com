/**
 * sync-redirects-to-kv.js
 *
 * Reads the `redirectMap` object already maintained in static/redirects.js and pushes every
 * entry into the Cloudflare Workers KV namespace used by cloudflare-worker-redirects.js — so
 * the Worker's real 301 redirects and the client-side JS fallback in redirects.js always stay
 * in sync from ONE source of truth (redirects.js), instead of maintaining two separate lists.
 *
 * This does an ADDITIVE sync (upserts every key from redirects.js into KV) — it never deletes
 * a KV entry that isn't in redirects.js anymore, since that's a rare/deliberate cleanup action
 * better done manually via the Cloudflare dashboard than automatically by a script.
 *
 * REQUIRES these environment variables:
 *   CLOUDFLARE_ACCOUNT_ID       — same account ID already used for Workers AI elsewhere in
 *                                  this project (tools/generate-articles.js etc.)
 *   CLOUDFLARE_API_TOKEN        — needs "Workers KV Storage: Edit" permission. Can be the same
 *                                  token already used elsewhere ONLY if that token's scope
 *                                  already includes KV edit; otherwise create a separate token
 *                                  at dash.cloudflare.com/profile/api-tokens with just that
 *                                  one permission, scoped to this account.
 *   CLOUDFLARE_KV_NAMESPACE_ID  — the namespace ID shown on the KV namespace's page in the
 *                                  dashboard (Workers & Pages → KV → your namespace), NOT the
 *                                  namespace's display name.
 *
 * USAGE:
 *   node sync-redirects-to-kv.js                → dry-run, prints what WOULD be synced
 *   node sync-redirects-to-kv.js --apply         → actually writes to KV
 */

const fs = require('fs');
const path = require('path');
const https = require('https');

const ARGS = process.argv.slice(2);
const APPLY = ARGS.includes('--apply');

const REDIRECTS_FILE = path.join(process.cwd(), 'static', 'redirects.js');

const ACCOUNT_ID = process.env.CLOUDFLARE_ACCOUNT_ID;
const API_TOKEN = process.env.CLOUDFLARE_API_TOKEN;
const NAMESPACE_ID = process.env.CLOUDFLARE_KV_NAMESPACE_ID;

function readRedirectMap() {
  if (!fs.existsSync(REDIRECTS_FILE)) {
    throw new Error(`${REDIRECTS_FILE} not found`);
  }
  const raw = fs.readFileSync(REDIRECTS_FILE, 'utf8');
  const mapMatch = raw.match(/const redirectMap = \{([\s\S]*?)\};/);
  if (!mapMatch) {
    throw new Error(`Could not find "const redirectMap = {...};" in ${REDIRECTS_FILE}`);
  }
  // Safe here: this file's object body is simple string-to-string data generated by our own
  // tooling (dedup-directional-suffix.js etc.), no untrusted input — evaluated once, locally.
  return Function('"use strict"; return ({' + mapMatch[1] + '})')();
}

function httpsRequest(hostname, reqPath, method, body, headers) {
  return new Promise((resolve, reject) => {
    const payload = body ? JSON.stringify(body) : undefined;
    const req = https.request({
      hostname,
      path: reqPath,
      method,
      headers: {
        'Content-Type': 'application/json',
        ...(payload ? { 'Content-Length': Buffer.byteLength(payload) } : {}),
        ...headers,
      },
    }, (res) => {
      let data = '';
      res.on('data', (c) => (data += c));
      res.on('end', () => {
        let parsed;
        try { parsed = JSON.parse(data); } catch { parsed = data; }
        resolve({ statusCode: res.statusCode, body: parsed });
      });
    });
    req.on('error', reject);
    if (payload) req.write(payload);
    req.end();
  });
}

async function main() {
  console.log(`\n🔄 sync-redirects-to-kv.js`);
  console.log(`   Mode: ${APPLY ? 'APPLY (will write to Cloudflare KV)' : 'DRY-RUN (preview only)'}`);

  const redirectMap = readRedirectMap();
  const entries = Object.entries(redirectMap);
  console.log(`📄 ${entries.length} entr${entries.length === 1 ? 'y' : 'ies'} found in static/redirects.js\n`);

  if (entries.length === 0) {
    console.log('✅ Nothing to sync.');
    return;
  }

  for (const [key, value] of entries) {
    console.log(`   ${key}  →  ${value}`);
  }

  if (!APPLY) {
    console.log(`\nℹ️  DRY-RUN — nothing written to KV. Re-run with --apply once this looks right.\n`);
    return;
  }

  if (!ACCOUNT_ID || !API_TOKEN || !NAMESPACE_ID) {
    console.error(`\n❌ Missing required environment variable(s):`);
    if (!ACCOUNT_ID) console.error('   - CLOUDFLARE_ACCOUNT_ID');
    if (!API_TOKEN) console.error('   - CLOUDFLARE_API_TOKEN');
    if (!NAMESPACE_ID) console.error('   - CLOUDFLARE_KV_NAMESPACE_ID');
    process.exit(1);
  }

  // Cloudflare's KV bulk-write endpoint accepts up to 10,000 key/value pairs per call — this
  // project's redirect list is nowhere near that, so a single call is always enough here, but
  // the chunking below keeps this script correct even if that ever changes.
  const CHUNK_SIZE = 10000;
  const kvPairs = entries.map(([key, value]) => ({ key, value }));

  let written = 0;
  for (let i = 0; i < kvPairs.length; i += CHUNK_SIZE) {
    const chunk = kvPairs.slice(i, i + CHUNK_SIZE);
    const result = await httpsRequest(
      'api.cloudflare.com',
      `/client/v4/accounts/${ACCOUNT_ID}/storage/kv/namespaces/${NAMESPACE_ID}/bulk`,
      'PUT',
      chunk,
      { Authorization: `Bearer ${API_TOKEN}` }
    );

    if (result.statusCode >= 200 && result.statusCode < 300 && result.body?.success) {
      written += chunk.length;
      console.log(`✅ Synced ${chunk.length} entr${chunk.length === 1 ? 'y' : 'ies'} to KV (batch starting at ${i}).`);
    } else {
      console.error(`❌ KV bulk write failed (HTTP ${result.statusCode}):`);
      console.error(JSON.stringify(result.body, null, 2));
      process.exit(1);
    }
  }

  console.log(`\n✅ Done — ${written} total entr${written === 1 ? 'y' : 'ies'} synced to Workers KV.\n`);
}

main().catch((err) => {
  console.error('\n💥 Fatal error:', err.message);
  process.exit(1);
});
